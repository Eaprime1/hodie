// Offline test for .github/scripts/latin-cue-record.js. No network, no GitHub.
// Run: node scripts/test_latin_cue_record.js

const rec = require('../.github/scripts/latin-cue-record.js');

const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
let failed = 0;
let total = 0;

function check(name, got, want) {
  total += 1;
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    failed += 1;
    process.stdout.write(`FAIL ${name}: ${JSON.stringify(got)} != ${JSON.stringify(want)}\n`);
  }
}

// Which calls a comment records: body, author type, association, expected names.
const cueRows = [
  ['caret seal', '^claude ultima probatio', 'User', 'OWNER', ['Ultima Probatio']],
  ['older at form', '@claude ultima probatio', 'User', 'OWNER', ['Ultima Probatio']],
  ['two calls', '^claude recensio\n^gemini lustratio', 'User', 'OWNER', ['Recensio', 'Lustratio']],
  ['same call twice', '^claude recensio\n^gemini recensio', 'User', 'OWNER', ['Recensio']],
  ['footer', `^claude recensio${FOOTER}`, 'User', 'OWNER', []],
  ['bot', '^claude recensio', 'Bot', 'OWNER', []],
  ['not owner', '^claude recensio', 'User', 'MEMBER', []],
  ['in code', '`^claude recensio`', 'User', 'OWNER', []],
  ['in quote', '> ^claude recensio', 'User', 'OWNER', []],
  ['plain words', 'a recensio of the notes', 'User', 'OWNER', []],
];
cueRows.forEach(([n, b, t, a, want]) => check(`cue: ${n}`, rec.cueNames(b, t, a), want));

check('stamp is UTC', rec.stamp('2026-10-16T09:05:59Z'), '202610160905');

const row = rec.rowFor({ at: '2026-10-16T09:05:00Z', cue: 'Recensio', by: 'owner', head: 'abc1234', source: '[comment](u)' });
check('row', row, '| 202610160905 | Recensio | @owner | `abc1234` | [comment](u) |');
check('last sha', rec.lastSha([row]), 'abc1234');
check('last sha, no rows', rec.lastSha([]), null);

const clean = { draft: false, mergeable_state: 'clean' };
const t0 = rec.tally([{ status: 'completed', conclusion: 'success' }, { status: 'completed', conclusion: 'skipped' }]);
check('tally passed', [t0.passed, t0.failed.length, t0.pending.length], [1, 0, 0]);
const t1 = rec.tally([{ status: 'completed', conclusion: 'failure' }, { status: 'in_progress' }]);
check('tally failed and running', [t1.passed, t1.failed.length, t1.pending.length], [0, 1, 1]);
check('ready when clean', rec.isReady(clean, t0, 0), true);
check('not ready with a failure', rec.isReady(clean, t1, 0), false);
check('not ready with an open thread', rec.isReady(clean, t0, 1), false);
check('not ready as a draft', rec.isReady({ draft: true, mergeable_state: 'clean' }, t0, 0), false);
check('not ready when blocked', rec.isReady({ draft: false, mergeable_state: 'blocked' }, t0, 0), false);

const body = rec.render({
  pr: clean, head: 'abc1234', tally: t1, open: 2, labels: ['final-oversight'],
  cue: 'Recensio', at: '202610160905', since: 'first cue on this PR', rows: [row],
});
check('render starts with the marker', body.startsWith(rec.MARK), true);
check('render keeps the rows', rec.oldRows(body), [row]);
check('render names the label', body.includes('`final-oversight`'), true);
check('render counts threads', body.includes('Unresolved review threads: 2'), true);
check('render marks not ready', body.includes('⬜ Ready'), true);
check('no rows without a log', rec.oldRows('plain'), []);
check('no rows from null', rec.oldRows(null), []);

// A fake GitHub that keeps the one record comment in `stored`.
function fakeGithub(stored) {
  const prData = { draft: false, mergeable_state: 'clean', head: { sha: 'abc1234def' }, labels: [] };
  const threads = { repository: { pullRequest: { reviewThreads: { pageInfo: { hasNextPage: false }, nodes: [] } } } };
  return {
    paginate: async (fn) => (fn === 'checks' ? [{ status: 'completed', conclusion: 'success' }] : stored),
    graphql: async () => threads,
    rest: {
      pulls: { get: async () => ({ data: prData }) },
      checks: { listForRef: 'checks' },
      issues: {
        listComments: 'comments',
        createComment: async ({ body }) => stored.push({ id: 1, user: { type: 'Bot' }, body }),
        updateComment: async ({ body }) => { stored[0].body = body; },
      },
      repos: { compareCommitsWithBasehead: async () => ({ data: { ahead_by: 2 } }) },
    },
  };
}

const ownerComment = (body) => ({
  body, user: { type: 'User', login: 'owner' }, author_association: 'OWNER',
  html_url: 'u', created_at: '2026-10-16T09:05:00Z',
});

// First cue creates the comment, the second updates it.
async function fullRun() {
  const stored = [];
  const github = fakeGithub(stored);
  const core = { info: () => {} };
  const context = { repo: { owner: 'o', repo: 'r' }, payload: { comment: ownerComment('^claude recensio'), issue: { number: 7 } } };
  await rec.run({ github, context, core });
  context.payload.comment = ownerComment('^claude probatio');
  await rec.run({ github, context, core });
  check('one comment kept', stored.length, 1);
  check('two rows logged', rec.oldRows(stored[0].body).length, 2);
}

fullRun().then(() => {
  process.stdout.write(`${total - failed} of ${total} passed\n`);
  process.exit(failed ? 1 : 0);
});
