#!/usr/bin/env bash
# Offline test of the seal-cue gate in .github/workflows/finalize-pr.yml.
# It pulls the real gate step out of the workflow, so it fails if the workflow
# drifts from what the gate is meant to catch. Needs bash, perl, python3 with
# PyYAML. Writes nothing to the repo.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
pass=0; fail=0
check() { if [ "$2" = "$3" ]; then pass=$((pass+1)); else fail=$((fail+1)); echo "FAIL: $1 (expected $2, got $3)"; fi; }

python3 - "$tmp/gate.sh" <<'PY'
import sys, yaml
d = yaml.safe_load(open('.github/workflows/finalize-pr.yml'))
step = [s for j in d['jobs'].values() for s in j['steps'] if s.get('id') == 'gate'][0]
open(sys.argv[1], 'w').write(step['run'])
PY
gate() {
  COMMENT_BODY="$1" GITHUB_OUTPUT="$tmp/out" bash "$tmp/gate.sh" >/dev/null 2>&1
  if grep -q 'triggered=true' "$tmp/out" 2>/dev/null; then echo seal; else echo skip; fi
  rm -f "$tmp/out"
}
BY=$'_Generated by [Claude Code](https://claude.ai/code)_'
WITH=$'\xf0\x9f\xa4\x96 Generated with [Claude Code](https://claude.com/claude-code)'
check "cue alone seals"                 seal "$(gate '@claude finalize')"
check "cue with trailing newline seals" seal "$(gate $'@claude finalize\r\n')"
check "cue on its own line seals"       seal "$(gate $'Ready.\n@claude finalize')"
check "footer 'by' skips"               skip "$(gate "@claude finalize $BY")"
check "footer 'with' skips"             skip "$(gate "@claude finalize $WITH")"
check "footer odd case skips"           skip "$(gate '@claude finalize GENERATED With [claude code]')"
check "quoted cue skips"                skip "$(gate '> @claude finalize')"
check "inline code cue skips"           skip "$(gate 'say `@claude finalize` when ready')"
check "fenced cue skips"                skip "$(gate $'```\n@claude finalize\n```')"
check "prose without cue skips"         skip "$(gate 'looks good, finalize later')"
check "word run-on does not seal"       skip "$(gate '@claude finalizer')"
echo "$pass of $((pass+fail)) passed"
[ "$fail" -eq 0 ]
